/**
 * One-shot: GeoJSON parish boundaries → compact SVG path module.
 * Source: TheLens geographic-data (Census TIGER-derived), public domain-ish geographic data.
 * Run: node scripts/generate-la-parish-map.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const sourcePath = path.join(__dirname, "la-parishes-source.json");
const outPath = path.join(root, "src", "data", "louisiana-parish-paths.ts");

const WIDTH = 720;
const HEIGHT = 680;
const PAD = 12;

const geo = JSON.parse(fs.readFileSync(sourcePath, "utf8"));

let minLon = Infinity;
let maxLon = -Infinity;
let minLat = Infinity;
let maxLat = -Infinity;

function visitCoords(coords, fn) {
  if (typeof coords[0] === "number") {
    fn(coords[0], coords[1]);
    return;
  }
  for (const c of coords) visitCoords(c, fn);
}

for (const f of geo.features) {
  visitCoords(f.geometry.coordinates, (lon, lat) => {
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  });
}

const spanLon = maxLon - minLon;
const spanLat = maxLat - minLat;
const scale = Math.min((WIDTH - PAD * 2) / spanLon, (HEIGHT - PAD * 2) / spanLat);
const offsetX = (WIDTH - spanLon * scale) / 2;
const offsetY = (HEIGHT - spanLat * scale) / 2;

function project(lon, lat) {
  const x = offsetX + (lon - minLon) * scale;
  const y = offsetY + (maxLat - lat) * scale;
  return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}

function ringToPath(ring) {
  if (!ring?.length) return "";
  const parts = [];
  for (let i = 0; i < ring.length; i++) {
    const [x, y] = project(ring[i][0], ring[i][1]);
    parts.push(`${i === 0 ? "M" : "L"}${x} ${y}`);
  }
  parts.push("Z");
  return parts.join("");
}

function geometryToPath(geometry) {
  if (geometry.type === "Polygon") {
    return geometry.coordinates.map(ringToPath).join("");
  }
  if (geometry.type === "MultiPolygon") {
    return geometry.coordinates
      .map((poly) => poly.map(ringToPath).join(""))
      .join("");
  }
  return "";
}

const parishes = geo.features
  .map((f) => ({
    name: String(f.properties.parishname),
    path: geometryToPath(f.geometry),
  }))
  .filter((p) => p.path)
  .sort((a, b) => a.name.localeCompare(b.name));

const file = `/* Generated by scripts/generate-la-parish-map.mjs — do not edit by hand. */
export const louisianaParishMap = {
  viewBox: "0 0 ${WIDTH} ${HEIGHT}",
  parishes: ${JSON.stringify(parishes, null, 2)} as const,
} as const;

export type LouisianaParishPath = (typeof louisianaParishMap.parishes)[number];
`;

fs.writeFileSync(outPath, file, "utf8");
console.log(`Wrote ${parishes.length} parish paths → ${path.relative(root, outPath)}`);
